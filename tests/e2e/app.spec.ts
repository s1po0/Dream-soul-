import { test, expect } from '@playwright/test'
import { SEED_CHARACTERS } from '../../src/lib/characters'

test.beforeEach(async ({ page }) => {
  await page.route('**/*.supabase.co/**', async route => {
    const path = new URL(route.request().url()).pathname
    if (path.startsWith('/rest/v1/characters')) return route.fulfill({ json: SEED_CHARACTERS })
    if (path === '/auth/v1/settings') return route.fulfill({ json: { external: { google: false }, disable_signup: false } })
    return route.fulfill({ status: 400, json: { error: 'invalid_credentials', msg: 'Invalid login credentials' } })
  })
})

test('Discover searches, filters, favorites, and has no phone overflow', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.locator('.character-card').first()).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('textbox', { name: 'Search characters' }).fill('Milo')
  await expect(page.locator('.character-card')).toHaveCount(1)
  await expect(page.locator('.character-card h3')).toHaveText('Milo')
  await page.getByRole('button', { name: 'Favorite Milo', exact: true }).click()
  await page.goto('/favorites')
  await expect(page.locator('.character-card')).toHaveCount(1)
  await page.getByRole('button', { name: 'Unfavorite Milo', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Keep your favorites close.' })).toBeVisible()
  await page.goto('/')
  await page.getByRole('button', { name: 'Helper', exact: true }).click()
  await expect(page.locator('.character-card h3')).toHaveText('Milo')
  await page.getByRole('button', { name: 'Reset filters' }).click()
  await expect(page.locator('.character-card')).toHaveCount(7)
  expect(errors).toEqual([])
})

test('18+ onboarding, create, streaming demo chat, edit, regenerate, restart, and report', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto('/onboarding?demo=true')
  await page.getByRole('textbox', { name: 'Your username' }).fill('little_dreamer')
  await page.getByRole('button', { name: 'Make myself at home' }).click()
  await expect(page).toHaveURL(/onboarding/)
  await page.getByRole('checkbox').check()
  await page.getByRole('button', { name: 'Make myself at home' }).click()
  await expect(page).toHaveURL(/\/$/)
  await page.goto('/create')
  await page.getByLabel('Character name').fill('Zephyr')
  await page.getByLabel('Their one-liner').fill('A curious soul in a library of stars.')
  await page.getByLabel('Personality & backstory').fill('Zephyr is a friendly adult librarian in an enchanted observatory. Warm, curious, witty, and always respectful. Loves maps and tea.')
  await page.getByLabel('Their first hello').fill('*A book floats down from the shelf.* “I was just saving you a seat. What shall we discover?”')
  await page.getByRole('button', { name: /Just between you two/ }).click()
  await page.getByRole('button', { name: 'Bring them to life' }).click()
  await expect(page).toHaveURL(/\/chat\//)
  await expect(page.locator('.message-bubble')).toHaveCount(1)
  const chatUrl = page.url()
  await page.getByRole('textbox', { name: 'Your message' }).fill('Hello, tell me about your library.')
  await page.getByRole('button', { name: 'Send message', exact: true }).click()
  await expect(page.locator('.typing-indicator')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Regenerate reply', exact: true })).toBeVisible()
  await expect(page.locator('.message-bubble')).toHaveCount(3)
  await expect(page.locator('.chat-demo-bar')).toContainText('Scripted replies')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Edit last message', exact: true }).click()
  await page.getByRole('textbox', { name: 'Edit your last message' }).fill('')
  await page.getByRole('textbox', { name: 'Edit your last message' }).pressSequentially('Where shall we travel tonight?', { delay: 65 })
  await expect(page.getByRole('textbox', { name: 'Edit your last message' })).toHaveValue('Where shall we travel tonight?')
  await page.getByRole('button', { name: 'Save & get a reply' }).click()
  await expect(page.getByRole('button', { name: 'Regenerate reply', exact: true })).toBeVisible()
  await expect(page.locator('.message-bubble-user')).toHaveText('Where shall we travel tonight?')
  const before = await page.locator('.message-bubble').last().innerText()
  await page.getByRole('button', { name: 'Regenerate reply', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Regenerate reply', exact: true })).toBeVisible()
  await expect(page.locator('.message-bubble').last()).not.toHaveText(before)
  await page.reload()
  await expect(page.locator('.message-bubble')).toHaveCount(3)
  await page.goto('/chats')
  await expect(page.locator('.chat-history-item')).toHaveCount(1)
  await page.goto(chatUrl)
  await page.getByRole('button', { name: 'Conversation options' }).click()
  await page.getByRole('button', { name: 'Start a new chapter' }).click()
  await page.getByRole('button', { name: 'Start fresh' }).click()
  await expect(page.locator('.message-bubble')).toHaveCount(1)
  await page.getByRole('button', { name: 'Conversation options' }).click()
  await page.getByRole('button', { name: 'Report character', exact: true }).click()
  await page.getByRole('textbox', { name: 'A little more detail' }).fill('Demo moderation flow test.')
  await page.getByRole('button', { name: 'Save demo report' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('dreamsoul:demo-reports') || '[]').length)).toBe(1)
  await page.getByRole('button', { name: 'Conversation options' }).click()
  await page.getByRole('button', { name: 'Block character', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Block character' }).click()
  await expect(page).toHaveURL(/\/$/)
  await page.goto('/profile')
  await page.getByRole('tab', { name: 'Settings' }).click()
  await page.getByRole('button', { name: /Blocked characters/ }).click()
  await page.getByRole('button', { name: 'Unblock all', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('tab', { name: 'My characters' }).click()
  await expect(page.locator('.own-character-wrap')).toHaveCount(1)
  await page.getByRole('link', { name: 'Edit their story' }).click()
  await page.getByLabel('Character name').fill('Zephyr Moonveil')
  await page.getByRole('button', { name: 'Save their story' }).click()
  await expect(page.locator('.chat-header-character')).toContainText('Zephyr Moonveil')
  expect(errors).toEqual([])
})

test('every main page fits the viewport, and safety and legal dialogs work', async ({ page }) => {
  for (const path of ['/', '/create', '/auth', '/profile', '/chats', '/terms', '/privacy']) {
    await page.goto(path)
    await expect(page.locator('main')).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `overflow at ${path}`).toBe(true)
  }
  await page.getByRole('button', { name: 'Safe space' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
})

